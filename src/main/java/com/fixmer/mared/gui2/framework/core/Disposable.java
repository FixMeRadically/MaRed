package com.fixmer.mared.gui2.framework.core;

/**
 * Умею освобождать ресурсы.
 *
 * 0.3.1: базовый контракт для компонентов и сервисов, у которых есть
 * подписки, кэши, открытые файлы. Контроллер (Studio, Project, ...)
 * вызывает dispose() при выгрузке.
 */
public interface Disposable {

    /** Освободить ресурсы. Идемпотентно — можно звать дважды. */
    void dispose();
}