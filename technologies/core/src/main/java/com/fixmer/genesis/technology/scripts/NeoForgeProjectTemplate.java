package com.fixmer.genesis.technology.scripts;
import java.util.*;
/** Pinned local starter project; no network, class loading or build execution. */
public final class NeoForgeProjectTemplate {
    private NeoForgeProjectTemplate() {}
    public static boolean validId(String id){return id!=null&&id.matches("[a-z][a-z0-9_]{1,47}")&&!Set.of("minecraft","neoforge","mared","javafml").contains(id);}
    public static String entry(String id){if(!validId(id))throw new IllegalArgumentException("Invalid mod id");return "src/main/java/genesis/generated/mod_"+id+"/ExampleMod.java";}
    public static Map<String,String> files(String id){
        if(!validId(id))throw new IllegalArgumentException("Use a unique lowercase mod id, 2-48 characters: a-z, 0-9, underscore");
        var files=new LinkedHashMap<String,String>();
        files.put("genesis-project.properties","format=1\nlanguage=JAVA\nmod_version=0.4.0\nworkspace=imported_gradle\ngradle_task=build\n");
        files.put("settings.gradle","pluginManagement { repositories { gradlePluginPortal(); maven { url = 'https://maven.neoforged.net/releases' } } }\nrootProject.name = '"+id+"'\n");
        files.put("gradle.properties","org.gradle.jvmargs=-Xmx3G\norg.gradle.daemon=false\norg.gradle.parallel=false\norg.gradle.configuration-cache=false\nmod_version=0.4.0\nneo_version=21.1.235\n");
        files.put("build.gradle", """
            plugins {
                id 'java-library'
                id 'net.neoforged.gradle.userdev' version '7.1.38'
            }
            version = mod_version
            group = 'genesis.generated.mod_%s'
            base { archivesName = '%s' }
            java.toolchain.languageVersion = JavaLanguageVersion.of(21)
            repositories { mavenCentral() }
            dependencies { implementation "net.neoforged:neoforge:${neo_version}" }
            runs {
                configureEach {
                    workingDirectory project.layout.projectDirectory.dir('run').dir(name)
                    modSource project.sourceSets.main
                }
                client { }
                server { argument '--nogui' }
            }
            tasks.withType(JavaCompile).configureEach { options.encoding = 'UTF-8' }
            tasks.withType(ProcessResources).configureEach {
                inputs.property('mod_version', project.mod_version)
                filesMatching('META-INF/neoforge.mods.toml') { expand mod_version: project.mod_version }
            }
            """.formatted(id,id));
        files.put(entry(id),"""
            package genesis.generated.mod_%s;
            import com.mojang.logging.LogUtils;
            import net.neoforged.bus.api.IEventBus;
            import net.neoforged.fml.ModContainer;
            import net.neoforged.fml.common.Mod;
            @Mod(ExampleMod.MOD_ID)
            public final class ExampleMod {
                public static final String MOD_ID = "%s";
                public ExampleMod(IEventBus modEventBus, ModContainer container) {
                    LogUtils.getLogger().info("{} loaded: built in Genesis", MOD_ID);
                }
            }
            """.formatted(id,id));
        files.put("src/main/resources/META-INF/neoforge.mods.toml", """
            modLoader="javafml"
            loaderVersion="[4,)"
            license="All Rights Reserved"
            [[mods]]
            modId="%s"
            version="${mod_version}"
            displayName="%s"
            description="A starter mod developed in Genesis."
            [[dependencies.%s]]
            modId="neoforge"
            type="required"
            versionRange="[21.1.235,)"
            ordering="NONE"
            side="BOTH"
            [[dependencies.%s]]
            modId="minecraft"
            type="required"
            versionRange="[1.21.1]"
            ordering="NONE"
            side="BOTH"
            """.formatted(id,id,id,id));
        files.put(".gitignore",".gradle/\nbuild/\nrun/\n.genesis-recovery/\n");
        files.put("README.md","# "+id+"\n\nMinecraft 1.21.1 / NeoForge 21.1.235 / JDK 21. Starter generated by Genesis 0.4.0.\n\nIn Scripts: save all (Ctrl+Alt+S), build (Ctrl+B), export (Z). Build creates build/libs/"+id+"-0.4.0.jar. Install the JAR into a matching NeoForge instance and restart it. The starter logs its mod id when loaded; it registers no items yet.\n\nOutside the game: set JAVA_HOME to a full JDK 21, run gradlew.bat build (Windows) or ./gradlew build (Unix). Dependencies and Gradle may download on first build. runClient/runServer start separate processes; server first start requires EULA acceptance. Never run a second server against an active world.\n\nThis project does not depend on MaRed or MR. Edit mod_version and metadata for your own release, and choose a license before distribution.\n");
        files.put("gradlew.bat","@echo off\r\nsetlocal\r\nset \"GENESIS_JAVA=java.exe\"\r\nif defined JAVA_HOME set \"GENESIS_JAVA=%JAVA_HOME%\\bin\\java.exe\"\r\n\"%GENESIS_JAVA%\" -classpath \"%~dp0gradle\\wrapper\\gradle-wrapper.jar\" org.gradle.wrapper.GradleWrapperMain %*\r\nexit /b %ERRORLEVEL%\r\n");
        files.put("gradlew","#!/bin/sh\nAPP_HOME=$(CDPATH= cd -- \"$(dirname -- \"$0\")\" && pwd) || exit 1\nif [ -n \"$JAVA_HOME\" ]; then GENESIS_JAVA=\"$JAVA_HOME/bin/java\"; else GENESIS_JAVA=java; fi\nexec \"$GENESIS_JAVA\" -classpath \"$APP_HOME/gradle/wrapper/gradle-wrapper.jar\" org.gradle.wrapper.GradleWrapperMain \"$@\"\n");
        return Collections.unmodifiableMap(files);
    }
}
